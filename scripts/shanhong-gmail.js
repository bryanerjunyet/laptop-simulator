function sortMailsByTime(mails) {
  return [...mails].sort((first, second) => getMailTimestamp(second.time) - getMailTimestamp(first.time));
}

function getMailTimestamp(time) {
  return new Date(time.replace(/\./g, "-").replace(" ", "T")).getTime();
}

